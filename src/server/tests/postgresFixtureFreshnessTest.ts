import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { initDatabase } from '../db';
import { getFirestoreDb } from '../firebase/admin';
import { ReadModelKeys, redisSetRaw, invalidateDataset, getPostgresFixtureReadModel, getAdminFixturesFromReadModel, getCompetitionFixturesFromReadModel, getFreshKey, redisIsDirty, clearProcessMemoryCache } from '../readModel/readModelStore';
import { createAiSnapshotReader } from '../services/telegramAiSnapshotReader';
import { getMyMatchesResilient } from '../services/myMatchesReadService';
import { firestoreCircuitBreaker } from '../firebase/circuitBreaker';
await initDatabase();
const db = getFirestoreDb();
process.env.DATABASE_PROVIDER = 'supabase';
process.env.SUPABASE_DATA_NAMESPACE = 'preview';
const seasonId = 'season-freshness-test';
const competitionId = 'comp-premier-league-2026';
const row = {id: 'live-game', seasonId, competitionId, homeClubId: 'club-arsenal', awayClubId: 'club-chelsea', matchday: 1, status: 'CONFIRMED', homeScore: 2, awayScore: 1};
await db.collection('fixtures').doc(row.id).set(row);
const key = ReadModelKeys.adminFixtures(seasonId);
await redisSetRaw(key, {data: [{...row,homeScore: 0,awayScore: 0}], generatedAt: '2026-10-09T00:00:00Z'});
await invalidateDataset(key);
const burst = await Promise.all(Array.from({length: 6}, () => getPostgresFixtureReadModel(seasonId)));
assert.ok(burst.every(r => !r.stale && r.data[0].homeScore === 2));
assert.equal(await redisIsDirty(key),false);
assert.equal((await getAdminFixturesFromReadModel({seasonId})).stale,false);
await db.collection('fixtures').doc('other-game').set({...row,id:'other-game',homeClubId:'club-liverpool',awayClubId:'club-everton'});
await invalidateDataset(key);
const mine = await getMyMatchesResilient('owner', [{id:'club-arsenal'} as any], seasonId);
assert.equal(mine.source,'postgresql');assert.equal(mine.stale,false);
assert.deepEqual(mine.fixtures.map(f => f.id),['live-game'],'Season cache must not leak another participant’s matches');

const competition = await getCompetitionFixturesFromReadModel(competitionId,{seasonId});
assert.equal(competition.fixtures[0].homeScore,2);
assert.equal(competition.stale,false);
const compKey = ReadModelKeys.competitionFixtures(competitionId,seasonId);
await db.collection('fixtures').doc(row.id).update({homeScore: 3});
await invalidateDataset(compKey);
const ai = await createAiSnapshotReader().read<any>(compKey);
assert.equal(ai.data[0].homeScore,3);
assert.equal(ai.stale,false,'AI refreshes invalidated datasets instead of permanently warning');
// Expiry refreshes too, without setting the old record fresh by extending its TTL.
const freshId = createHash('sha256').update(getFreshKey(compKey)).digest('hex');
await db.collection('durable_read_snapshots').doc(freshId).update({expiresAt: Date.now()-1});
await db.collection('fixtures').doc(row.id).update({homeScore: 4});
clearProcessMemoryCache();
assert.equal((await createAiSnapshotReader().read<any>(compKey)).data[0].homeScore,4);
const empty = await getPostgresFixtureReadModel(seasonId,'comp-empty');
assert.deepEqual(empty.data,[]);assert.equal(empty.stale,false);
// An outage keeps its warning and LKG; never claims the cached score is current.
await invalidateDataset(compKey);
firestoreCircuitBreaker.forceState('OPEN');
const fallback = await createAiSnapshotReader().read<any>(compKey);
assert.equal(fallback.data[0].homeScore,4);assert.equal(fallback.stale,true);
console.log('PASS PostgreSQL fixture cold/invalidation/expiry refresh, shared refresh, admin and AI freshness, empty schedule and honest outage fallback');
