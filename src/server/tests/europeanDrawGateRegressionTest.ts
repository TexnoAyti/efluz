import assert from 'node:assert/strict';
import {getFirestoreDb} from '../firebase/admin';
import {initDatabase} from '../db';
import {SEED_COMPETITIONS,SEED_CLUBS} from '../db/seed';
import {generateRoundRobinSchedule} from '../tournament/fixtureEngine';
import {previewEuropeanQualificationSync,applyEuropeanQualificationSync} from '../tournament/qualificationEngine';
import {generateCompetitionFixturesFirestore,getFixturesFirestore,getFixtureByIdFirestore} from '../firebase/firestoreStore';
import {domesticSeasonComplete,filterPublishedEuropeanFixtures} from '../services/europeanFixtureGate';
import {controlCompetitionMatchday} from '../services/competitionMatchdayService';
import {withVisibleFixtureCounts} from '../services/competitionFixtureCounts';
import {getMyMatchesResilient} from '../services/myMatchesReadService';
import {ReadModelKeys,redisSetRaw,getCompetitionFixturesFromReadModel} from '../readModel/readModelStore';

await initDatabase();
const db=getFirestoreDb(), seasonId='season-2026-27',id='comp-champions-league-2026';
process.env.DATABASE_PROVIDER='supabase';process.env.SUPABASE_DATA_NAMESPACE='preview';
for(const comp of SEED_COMPETITIONS) await db.collection('competitions').doc(comp.id).set(comp);
const comp=SEED_COMPETITIONS.find(c=>c.id===id)!;
const legacy:any={id:'legacy-ucl',competitionId:id,seasonId,matchday:1,status:'SCHEDULED',homeClubId:'club-arsenal',awayClubId:'club-chelsea'};
await db.collection('fixtures').doc(legacy.id).set(legacy);
await redisSetRaw(ReadModelKeys.competitionFixtures(id,seasonId),{data:[legacy],actualCount:1,generatedAt:new Date().toISOString()});
await redisSetRaw(ReadModelKeys.adminFixtures(seasonId),{data:[legacy],actualCount:1,generatedAt:new Date().toISOString()});
assert.equal((await filterPublishedEuropeanFixtures([legacy])).length,0);
assert.equal((await getFixturesFirestore({competitionId:id,seasonId})).length,0);
assert.equal(await getFixtureByIdFirestore(legacy.id),null);
assert.equal((await getCompetitionFixturesFromReadModel(id,{seasonId})).fixtures.length,0,'Warm old snapshots cannot expose a pre-draw fixture');
assert.equal((await getMyMatchesResilient('owner',[SEED_CLUBS.find(c=>c.id==='club-arsenal')!] as any,seasonId)).fixtures.length,0);
assert.equal((await withVisibleFixtureCounts([comp as any],seasonId))[0].fixturesCount,0);
for(const force of [false,true]) await assert.rejects(generateCompetitionFixturesFirestore(id,{force}),/avval barcha ichki liga/);
await assert.rejects(controlCompetitionMatchday(id,{action:'OPEN',matchday:1}),/yakuniy saralash/);
assert.equal((await db.collection('fixtures').doc(legacy.id).get()).exists,true,'Premature fixtures are preserved, not deleted by a blocked draw');
assert.equal((await previewEuropeanQualificationSync(seasonId,'final')).canApply,false);
const provisional=await previewEuropeanQualificationSync(seasonId,'provisional');
await applyEuropeanQualificationSync({previewToken:provisional.previewToken,seasonId,confirmation:true,adminUserId:'admin'});
const domestic=SEED_COMPETITIONS.filter(c=>c.type==='LEAGUE');
const rows=domestic.flatMap(c=>generateRoundRobinSchedule(SEED_CLUBS.filter(t=>t.leagueId===c.leagueId).map(t=>t.id),{homeAndAway:false}).map((m,i)=>({...m,id:`domestic-${c.id}-${i}`,competitionId:c.id,seasonId,status:'CONFIRMED',homeScore:0,awayScore:0})));
assert.equal(domesticSeasonComplete(domestic,rows,seasonId),true);
assert.equal(domesticSeasonComplete(domestic,rows.slice(1),seasonId),false,'Missing domestic schedule cannot count as complete');
assert.equal(domesticSeasonComplete(domestic,[...rows.slice(1),rows[1]],seasonId),false,'Duplicate pairs cannot mask missing games');
for(let i=0;i<rows.length;i+=400){const batch=db.batch();for(const row of rows.slice(i,i+400))batch.set(db.collection('fixtures').doc(row.id),row);await batch.commit();}
await assert.rejects(generateCompetitionFixturesFirestore(id),/yakuniy Yevropa saralashini/,'Provisional qualification does not authorize a draw');
const final=await previewEuropeanQualificationSync(seasonId,'final');assert.equal(final.canApply,true);
await applyEuropeanQualificationSync({previewToken:final.previewToken,seasonId,confirmation:true,adminUserId:'admin'});
assert.equal((await filterPublishedEuropeanFixtures([legacy])).length,0,'Final qualification alone is not the draw');
const draw=await generateCompetitionFixturesFirestore(id);assert.equal(draw.generated,128);
const current=(await db.collection('competitions').doc(id).get()).data()!;
assert.equal(current.europeanDrawQualificationToken,final.previewToken);
const fixtures=(await db.collection('fixtures').where('competitionId','==',id).get()).docs.map(d=>d.data());
assert.equal((await filterPublishedEuropeanFixtures(fixtures as any)).length,128);
assert.equal((await filterPublishedEuropeanFixtures([legacy])).length,0,'An old snapshot stays hidden after publication');
assert.equal((await getFixturesFirestore({competitionId:id,seasonId})).length,128);
await db.collection('fixtures').doc(rows[0].id).update({status:'SCHEDULED'});
await assert.rejects(generateCompetitionFixturesFirestore(id,{force:true}),/avval barcha ichki liga/);
console.log('PASS European gate: incomplete/missing/duplicate domestic schedules, provisional vs final qualification, force bypass blocked, legacy fixture+warm snapshot+my matches hidden, locked round, finalization alone hidden, tagged 128-match draw published, reopened domestic result blocks redraw.');
